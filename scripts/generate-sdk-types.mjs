// Generates the SDK's wire types from the backend's OpenAPI document.
//
//   node scripts/generate-sdk-types.mjs          write sdk/src/contract.ts
//   node scripts/generate-sdk-types.mjs --check  fail when it is out of date
//
// Only the JSON Schema subset used by the contract is supported; anything else
// fails loudly so the generator is extended deliberately.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = new URL("../backend/internal/api/openapi.json", import.meta.url);
const TARGET = new URL("../sdk/src/contract.ts", import.meta.url);
const KEYWORDS = new Set(["type", "properties", "required", "items", "$ref", "enum", "additionalProperties", "format", "description", "const"]);
const PRIMITIVES = { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null" };

const identifier = (name) => /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
const comment = (text, indent) => text ? `${indent}/** ${text.replace(/\*\//g, "*\\/")} */\n` : "";

function render(schema, path, indent) {
  for (const key of Object.keys(schema)) {
    if (!KEYWORDS.has(key)) throw new Error(`${path}: unsupported schema keyword "${key}"`);
  }
  if (schema.$ref) {
    const name = schema.$ref.replace(/^#\/components\/schemas\//, "");
    if (name === schema.$ref) throw new Error(`${path}: unsupported reference ${schema.$ref}`);
    return `Schemas[${JSON.stringify(name)}]`;
  }
  if ("const" in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  const types = schema.type === undefined ? [] : [schema.type].flat();
  // An empty schema accepts any JSON value.
  if (types.length === 0) return "unknown";
  const rendered = types.map((type) => {
    if (type in PRIMITIVES) return PRIMITIVES[type];
    if (type === "array") {
      if (!schema.items) throw new Error(`${path}: array has no items`);
      const item = render(schema.items, `${path}[]`, indent);
      return /[ |]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    if (type === "object") return renderObject(schema, path, indent);
    throw new Error(`${path}: unsupported type "${type}"`);
  });
  return rendered.join(" | ");
}

function renderObject(schema, path, indent) {
  const required = new Set(schema.required ?? []);
  const inner = indent + "  ";
  const members = Object.entries(schema.properties ?? {}).map(([name, property]) =>
    comment(property.description, inner) +
    `${inner}${identifier(name)}${required.has(name) ? "" : "?"}: ${render(property, `${path}.${name}`, inner)};\n`);
  const additional = schema.additionalProperties;
  if (additional && typeof additional === "object") {
    members.push(`${inner}[key: string]: ${render(additional, `${path}{}`, inner)};\n`);
  } else if (members.length === 0 && additional !== false) {
    return "Record<string, unknown>";
  }
  return members.length ? `{\n${members.join("")}${indent}}` : "Record<string, never>";
}

export function generate(document) {
  const schemas = Object.entries(document.components.schemas)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, schema]) => comment(schema.description, "  ") + `  ${identifier(name)}: ${render(schema, name, "  ")};\n`);
  return `// Generated by scripts/generate-sdk-types.mjs from backend/internal/api/openapi.json.
// Do not edit; change the contract and run \`npm run generate:types\`.

/** Wire shapes of the HTTP contract, keyed by OpenAPI schema name. */
export type Schemas = {
${schemas.join("")}};

export type Schema<Name extends keyof Schemas> = Schemas[Name];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = generate(JSON.parse(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(TARGET, "utf8"); } catch { /* reported below */ }
    if (current !== output) {
      console.error("sdk/src/contract.ts is out of date; run `npm run generate:types`.");
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, output);
  }
}
